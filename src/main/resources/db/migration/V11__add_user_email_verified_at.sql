-- 예매하기 전에 가입 이메일의 주인임을 인증했는지 남긴다. NULL 이면 미인증이다.
-- 인증번호는 몇 분 뒤 사라져도 되는 값이라 Redis 에 두지만, 인증을 마쳤다는 사실은 영구히 남아야 해서 DB 컬럼이다.
-- 언제 인증했는지까지 남겨서 문의가 오면 근거로 쓴다. (BOOLEAN 이면 한 것만 알고 언제 했는지는 모른다)
-- 기존 회원을 인증된 것으로 채우지 않는다. 인증하지 않은 사람을 인증한 것으로 만드는 기록을 남기지 않으려는 것이다.
ALTER TABLE user_member
    ADD COLUMN email_verified_at TIMESTAMP;
