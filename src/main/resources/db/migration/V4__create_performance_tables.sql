-- 3부 공연 영역: 취소 규정, 공연, 등급, 회차, 회차별 판매 좌석, 연기 이력, 공통 안내.
-- FK 는 논리 FK 라서 DB 제약을 걸지 않는다. 대신 자주 조회하는 컬럼에는 인덱스를 만든다.
-- 만드는 순서는 doc/appendix.md 부록 C 를 따른다.

-- 취소 규정. business_id 가 비어 있으면 서비스 기본 규정이다.
CREATE TABLE cancel_policy (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT,
    name         VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP    NOT NULL
);

CREATE INDEX idx_cancel_policy_business ON cancel_policy (business_id);

-- 취소 규정 구간 (공연 N일 전 이상 ~ N일 전 이하의 수수료율)
CREATE TABLE cancel_policy_rule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id   BIGINT   NOT NULL,
    days_from   INTEGER  NOT NULL,
    -- 비어 있으면 제한 없음
    days_to     INTEGER,
    fee_rate    INTEGER  NOT NULL,
    cancelable  BOOLEAN  NOT NULL
);

CREATE INDEX idx_cancel_policy_rule_policy ON cancel_policy_rule (policy_id);

-- 서비스 기본 취소 규정. 공연은 cancel_policy_id 가 필수라서 처음부터 있어야 하고,
-- 판매자는 이 규정을 복사해서 자기 사업체 규정으로 고친다. (데모 데이터가 아니라 운영에도 필요한 기준 데이터)
INSERT INTO cancel_policy (business_id, name, created_at) VALUES (NULL, '기본 규정', NOW());

INSERT INTO cancel_policy_rule (policy_id, days_from, days_to, fee_rate, cancelable)
SELECT p.id, r.days_from, r.days_to, r.fee_rate, r.cancelable
FROM cancel_policy p,
     (VALUES (7, NULL::INTEGER, 0, TRUE),
             (3, 6, 10, TRUE),
             (1, 2, 20, TRUE),
             (0, 0, 0, FALSE)) AS r(days_from, days_to, fee_rate, cancelable)
WHERE p.business_id IS NULL AND p.name = '기본 규정';

-- 공연. 판매 상태는 회차에 두고, 공연은 작성 중 / 공개 / 취소만 가진다.
CREATE TABLE performance (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id      BIGINT        NOT NULL,
    venue_id         BIGINT        NOT NULL,
    created_by       BIGINT        NOT NULL,
    cancel_policy_id BIGINT        NOT NULL,
    title            VARCHAR(200)  NOT NULL,
    genre            VARCHAR(20)   NOT NULL,
    age_limit        INTEGER       NOT NULL,
    running_time     INTEGER       NOT NULL,
    cast_info        TEXT,
    poster_url       VARCHAR(2048) NOT NULL,
    notice           TEXT,
    guide            TEXT,
    status           VARCHAR(20)   NOT NULL,
    -- 판매 오픈·종료와 1인 최대 매수는 모든 회차가 같다.
    sale_open_at     TIMESTAMP     NOT NULL,
    sale_close_at    TIMESTAMP     NOT NULL,
    max_per_person   INTEGER       NOT NULL,
    receive_type     VARCHAR(20)   NOT NULL,
    -- 티켓 1장당 원. 판매자가 공연마다 정한다.
    booking_fee      INTEGER       NOT NULL,
    created_at       TIMESTAMP     NOT NULL,
    updated_at       TIMESTAMP     NOT NULL
);

-- 판매자의 내 공연 목록, 공연장별 조회, 예매자의 공연 목록 필터
CREATE INDEX idx_performance_business ON performance (business_id);
CREATE INDEX idx_performance_venue ON performance (venue_id);
CREATE INDEX idx_performance_status_genre ON performance (status, genre);

-- 공연 상세 설명용 이미지 (포스터는 performance.poster_url)
CREATE TABLE performance_image (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id  BIGINT         NOT NULL,
    url             VARCHAR(2048)  NOT NULL,
    sort_order      INTEGER        NOT NULL
);

CREATE INDEX idx_performance_image_performance ON performance_image (performance_id, sort_order);

-- 좌석 등급. 같은 공연장이라도 공연마다 가격 체계가 달라서 공연 단위로 만든다.
CREATE TABLE seat_grade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id  BIGINT       NOT NULL,
    name            VARCHAR(50)  NOT NULL,
    price           INTEGER      NOT NULL,
    color           VARCHAR(20)
);

CREATE INDEX idx_seat_grade_performance ON seat_grade (performance_id);

-- 구역별 등급. 한 공연에서 한 구역은 한 번만 지정할 수 있다. 지정하지 않은 구역은 판매하지 않는다.
CREATE TABLE zone_grade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id  BIGINT  NOT NULL,
    zone_id         BIGINT  NOT NULL,
    grade_id        BIGINT  NOT NULL
);

CREATE UNIQUE INDEX uq_zone_grade_performance_zone ON zone_grade (performance_id, zone_id);
CREATE INDEX idx_zone_grade_grade ON zone_grade (grade_id);

-- 공연 회차. 판매 상태는 회차가 가진다. (한 회차만 연기하는 경우를 표현하려고)
CREATE TABLE performance_schedule (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    performance_id      BIGINT       NOT NULL,
    start_at            TIMESTAMP    NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    pause_reason        VARCHAR(255),
    -- 판매 좌석(schedule_seat)을 만든 시각. 비어 있으면 아직 안 만든 회차
    seats_generated_at  TIMESTAMP,
    created_at          TIMESTAMP    NOT NULL,
    updated_at          TIMESTAMP    NOT NULL
);

CREATE INDEX idx_performance_schedule_performance ON performance_schedule (performance_id, start_at);
-- 판매 좌석 생성 스케줄러가 "아직 안 만든 회차"만 빠르게 찾는다.
CREATE INDEX idx_performance_schedule_not_generated ON performance_schedule (performance_id)
    WHERE seats_generated_at IS NULL;

-- 회차별 판매 좌석. 동시성, 대기열, 매진 처리가 모두 이 테이블 위에서 일어나는 핵심 테이블이다.
CREATE TABLE schedule_seat (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id    BIGINT       NOT NULL,
    venue_seat_id  BIGINT       NOT NULL,
    -- 구역별 조회를 조인 없이 하려고 복사해 둔다.
    zone_id        BIGINT       NOT NULL,
    -- 판매 제외 좌석은 등급과 가격이 비어 있다.
    grade_id       BIGINT,
    price          INTEGER,
    status         VARCHAR(20)  NOT NULL,
    held_by        BIGINT,
    held_until     TIMESTAMP,
    -- 낙관적 락 방식을 비교 실험할 때 쓴다. 기본 방어는 SELECT ... FOR UPDATE 다.
    version        INTEGER      NOT NULL,
    updated_at     TIMESTAMP    NOT NULL
);

-- 같은 회차에서 같은 좌석이 두 번 만들어지지 않게 한다. (좌석 생성 실패 후 재시도에도 안전하다)
CREATE UNIQUE INDEX uq_schedule_seat_venue_seat ON schedule_seat (schedule_id, venue_seat_id);
-- 구역 요약(잔여석)과 구역 상세 조회
CREATE INDEX idx_schedule_seat_zone_status ON schedule_seat (schedule_id, zone_id, status);
-- 만료된 점유 정리. 점유 중인 좌석만 담겨서 작다.
CREATE INDEX idx_schedule_seat_held_until ON schedule_seat (held_until) WHERE status = 'HELD';

-- UPDATE 가 많은 테이블이라 행에 여유 공간을 두고 청소(autovacuum)를 더 자주 돌린다. (수치는 부하 테스트로 조정)
ALTER TABLE schedule_seat SET (fillfactor = 80, autovacuum_vacuum_scale_factor = 0.02);

-- 회차 연기 이력. 한 회차에 연기가 여러 번 쌓일 수 있고, 판단은 최신 이력만 본다.
CREATE TABLE schedule_postponement (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id        BIGINT        NOT NULL,
    old_start_at       TIMESTAMP     NOT NULL,
    -- 비어 있으면 새 일정 미정
    new_start_at       TIMESTAMP,
    reason             VARCHAR(500)  NOT NULL,
    -- 이 시각까지는 수수료 없이 취소할 수 있다.
    free_cancel_until  TIMESTAMP     NOT NULL,
    changed_by         BIGINT        NOT NULL,
    created_at         TIMESTAMP     NOT NULL
);

CREATE INDEX idx_schedule_postponement_schedule ON schedule_postponement (schedule_id, created_at);

-- 공통 안내. 모든 공연에 똑같이 보여주고, 유형마다 한 행만 둔다. 관리자만 수정한다.
CREATE TABLE common_guide (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20)  NOT NULL,
    content     TEXT         NOT NULL,
    updated_by  BIGINT       NOT NULL,
    updated_at  TIMESTAMP    NOT NULL
);

CREATE UNIQUE INDEX uq_common_guide_type ON common_guide (type);
