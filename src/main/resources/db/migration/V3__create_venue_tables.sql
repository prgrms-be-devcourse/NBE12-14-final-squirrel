-- 2부 공연장 영역: 공연장, 구역, 좌석, 공연장 신청.
-- FK 는 논리 FK 라서 DB 제약을 걸지 않는다. 대신 자주 조회하는 컬럼에는 인덱스를 만든다.
-- (버전 번호는 db/migration 과 db/seed 가 같은 순번을 공유한다. V2 는 시드가 쓰고 있다.)

-- 공연장 (삭제하지 않고 status 로 사용 중지한다)
CREATE TABLE venue (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    address      VARCHAR(255) NOT NULL,
    region       VARCHAR(50)  NOT NULL,
    -- 좌석 생성 스크립트가 만든 좌석 수를 세서 넣는다.
    total_seats  INTEGER      NOT NULL,
    -- 프론트가 도면을 고르는 이름표. 비어 있으면 기본 격자 도면
    layout_key   VARCHAR(50),
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL
);

-- 지역별 공연장 검색, 사용 중인 공연장만 보여주기
CREATE INDEX idx_venue_region_status ON venue (region, status);

-- 공연장 구역 (가격과 등급을 구역 단위로 정한다)
CREATE TABLE venue_zone (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id    BIGINT       NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    floor       VARCHAR(20),
    sort_order  INTEGER      NOT NULL
);

CREATE INDEX idx_venue_zone_venue ON venue_zone (venue_id, sort_order);

-- 공연장 좌석 원본. 열·번호가 문자일 수 있어서 문자열로 두고 표시 순서는 sort_order 로 따로 저장한다.
CREATE TABLE venue_seat (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id     BIGINT       NOT NULL,
    zone_id      BIGINT       NOT NULL,
    row_label    VARCHAR(30)  NOT NULL,
    seat_number  VARCHAR(30)  NOT NULL,
    sort_order   INTEGER      NOT NULL
);

-- 같은 구역 안에서 (열, 번호) 조합은 중복될 수 없다.
CREATE UNIQUE INDEX uq_venue_seat_position ON venue_seat (zone_id, row_label, seat_number);
-- 판매 좌석을 복사할 때 공연장 단위로 읽는다.
CREATE INDEX idx_venue_seat_venue ON venue_seat (venue_id);

-- 공연장 신청. 소통은 사이트 밖(메일, 전화)에서 하고 신청 기록과 상태만 남긴다.
CREATE TABLE venue_request (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT       NOT NULL,
    requested_by   BIGINT       NOT NULL,
    venue_name     VARCHAR(100) NOT NULL,
    address        VARCHAR(255),
    contact_phone  VARCHAR(20)  NOT NULL,
    contact_email  VARCHAR(255) NOT NULL,
    description    TEXT,
    status         VARCHAR(20)  NOT NULL,
    admin_memo     TEXT,
    reject_reason  VARCHAR(500),
    handled_by     BIGINT,
    -- 등록 완료 후 만들어진 공연장. 완료 전에는 비어 있다.
    venue_id       BIGINT,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL
);

CREATE INDEX idx_venue_request_business ON venue_request (business_id);
CREATE INDEX idx_venue_request_status ON venue_request (status);
