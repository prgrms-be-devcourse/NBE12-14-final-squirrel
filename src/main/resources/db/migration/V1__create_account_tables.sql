-- 1부 유저 영역: 예매자, 판매자, 관리자 계정과 약관.
-- FK 는 논리 FK 라서 DB 제약을 걸지 않는다. 대신 자주 조회하는 컬럼에는 인덱스를 만든다.
-- 만드는 순서는 doc/appendix.md 부록 C 를 따른다.

-- 예매자
CREATE TABLE user_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    name         VARCHAR(50)  NOT NULL,
    nickname     VARCHAR(50)  NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    profile_img  VARCHAR(2048),
    ci_hash      VARCHAR(64),
    birth_date   DATE,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    deleted_at   TIMESTAMP
);

-- 탈퇴한 회원은 중복 검사에서 빠진다. (탈퇴 후 같은 이메일·같은 사람의 재가입을 허용)
-- 이메일은 저장 전에 소문자로 맞추므로 대소문자 구분 없이 중복이 걸린다.
CREATE UNIQUE INDEX uq_user_email ON user_member (email) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_user_ci ON user_member (ci_hash) WHERE deleted_at IS NULL;

-- 약관 (개정하면 새 행을 추가한다)
CREATE TABLE terms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20) NOT NULL,
    version     VARCHAR(20) NOT NULL,
    content     TEXT        NOT NULL,
    required    BOOLEAN     NOT NULL,
    created_at  TIMESTAMP   NOT NULL
);

CREATE UNIQUE INDEX uq_terms_type_version ON terms (type, version);

-- 누가 어떤 약관에 동의했는지
CREATE TABLE user_terms_agreement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL,
    terms_id   BIGINT    NOT NULL,
    agreed_at  TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX uq_user_terms_agreement ON user_terms_agreement (user_id, terms_id);
CREATE INDEX idx_user_terms_agreement_terms ON user_terms_agreement (terms_id);

-- 관리자 (가입 없이 시드로 넣는다)
CREATE TABLE admin_member (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(255) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    deleted_at  TIMESTAMP
);

CREATE UNIQUE INDEX uq_admin_email ON admin_member (email) WHERE deleted_at IS NULL;

-- 판매자 사업체 (승인 대상)
CREATE TABLE seller_business (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name          VARCHAR(100) NOT NULL,
    representative_name   VARCHAR(50)  NOT NULL,
    business_number       VARCHAR(20)  NOT NULL,
    contact_phone         VARCHAR(20)  NOT NULL,
    contact_email         VARCHAR(255) NOT NULL,
    terms_agreed_at       TIMESTAMP    NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    reject_reason         VARCHAR(500),
    reviewed_by           BIGINT,
    reviewed_at           TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP    NOT NULL
);

CREATE UNIQUE INDEX uq_seller_business_number ON seller_business (business_number);
CREATE INDEX idx_seller_business_status ON seller_business (status);

-- 판매자 계정 (대표 OWNER, 담당자 STAFF)
CREATE TABLE seller_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    name         VARCHAR(50)  NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    role         VARCHAR(20)  NOT NULL,
    ci_hash      VARCHAR(64)  NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP    NOT NULL,
    deleted_at   TIMESTAMP
);

CREATE UNIQUE INDEX uq_seller_email ON seller_member (email) WHERE deleted_at IS NULL;
-- 같은 사람이 한 사업체에 두 번 들어오는 것만 막는다. (다른 사업체는 막지 않음)
CREATE UNIQUE INDEX uq_seller_business_ci ON seller_member (business_id, ci_hash);
-- 대표자는 사업체당 1명
CREATE UNIQUE INDEX uq_seller_business_owner ON seller_member (business_id) WHERE role = 'OWNER';

-- 담당자 초대 링크
CREATE TABLE seller_invitation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id  BIGINT       NOT NULL,
    invited_by   BIGINT       NOT NULL,
    email        VARCHAR(255) NOT NULL,
    token        VARCHAR(100) NOT NULL,
    expires_at   TIMESTAMP    NOT NULL,
    used_at      TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL
);

CREATE UNIQUE INDEX uq_seller_invitation_token ON seller_invitation (token);
CREATE INDEX idx_seller_invitation_business ON seller_invitation (business_id);
