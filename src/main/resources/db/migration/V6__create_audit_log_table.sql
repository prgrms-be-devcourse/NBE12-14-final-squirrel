-- 5부 운영 영역: 감사 로그.
-- 판매자·관리자·시스템의 변경 행동만 추가한다. 수정·삭제하지 않는다.
-- 행위자(판매자, 관리자, 시스템)와 대상(공연, 회차, 환불 ...)이 제각각이라 FK 대신 종류 + 번호로 가리킨다.
-- 계정이나 공연이 지워져도 로그는 남아야 하기 때문이다.

CREATE TABLE audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type    VARCHAR(20)  NOT NULL,
    -- 시스템 행동이면 비운다.
    actor_id      BIGINT,
    -- 판매자 이력 조회용. 관리자·시스템 행동은 비울 수 있다.
    business_id   BIGINT,
    target_type   VARCHAR(50)  NOT NULL,
    target_id     BIGINT       NOT NULL,
    action        VARCHAR(50)  NOT NULL,
    before_value  JSONB,
    after_value   JSONB,
    created_at    TIMESTAMP    NOT NULL
);

-- 판매자 이력 조회 (자기 사업체 로그만)
CREATE INDEX idx_audit_log_business_created ON audit_log (business_id, created_at DESC);
-- 특정 대상의 변경 이력
CREATE INDEX idx_audit_log_target ON audit_log (target_type, target_id);
