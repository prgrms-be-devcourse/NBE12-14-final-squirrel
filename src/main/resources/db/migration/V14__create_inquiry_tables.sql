-- 문의. 예매자·판매자가 한 테이블을 함께 쓰고 관리자가 답변한다. (doc/inquiry-design.md)
-- 예매자와 판매자는 계정 테이블이 달라 번호가 겹칠 수 있어서, 작성자는 항상 종류(author_type) + 번호(author_id)로 가리킨다.
-- 판매자 문의는 다음 PR 이지만 컬럼을 다시 추가하지 않으려고 판매자 컬럼(business_id)까지 미리 만든다.
CREATE TABLE inquiry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_type   VARCHAR(20)   NOT NULL,
    author_id     BIGINT        NOT NULL,
    -- 판매자 문의만. 같은 사업체의 대표·담당자가 함께 본다.
    business_id   BIGINT,
    -- 작성자가 예매자·판매자 테이블로 나뉘어 연관관계 하나로 이름을 꺼낼 수 없어서 쓸 때 복사해 둔다.
    author_name   VARCHAR(50)   NOT NULL,
    author_email  VARCHAR(255)  NOT NULL,
    category      VARCHAR(30)   NOT NULL,
    -- 예매자 문의에서 고른 내 예매. 고르지 않으면 비운다.
    booking_id    BIGINT,
    title         VARCHAR(100)  NOT NULL,
    content       VARCHAR(2000) NOT NULL,
    -- 첨부 사진 주소 목록(JSON 배열, 최대 3장). 문의와 늘 같이 읽고 쓰며 수정할 때도 통째로 바꾸고,
    -- 사진 하나로 검색할 일이 없어서 테이블을 나누지 않는다. 사진이 없으면 빈 배열이다.
    image_urls    JSONB         NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    -- 답변은 하나라 같은 행에 둔다. 답변 전에는 비어 있다.
    answer        VARCHAR(2000),
    answered_by   BIGINT,
    answered_at   TIMESTAMP,
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    deleted_at    TIMESTAMP
);

-- 문의 이력. 작성·수정·삭제·답변마다 그 순간의 내용을 통째로 남긴다. 수정·삭제하지 않는다.
-- 답변 전 수정은 본문을 덮어쓰므로, 처음에 무엇을 썼는지와 관리자가 어떤 내용에 답했는지는 여기에만 남는다.
CREATE TABLE inquiry_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id   BIGINT         NOT NULL,
    actor_type   VARCHAR(20)    NOT NULL,
    actor_id     BIGINT         NOT NULL,
    action       VARCHAR(20)    NOT NULL,
    title        VARCHAR(100)   NOT NULL,
    content      VARCHAR(2000)  NOT NULL,
    image_urls   JSONB          NOT NULL,
    answer       VARCHAR(2000),
    created_at   TIMESTAMP      NOT NULL
);
