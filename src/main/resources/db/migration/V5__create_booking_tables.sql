-- 4부 예매·결제 영역: 예매, 예매 좌석, 결제, 환불.
-- FK 는 논리 FK 라서 DB 제약을 걸지 않는다. 대신 자주 조회하는 컬럼에는 인덱스를 만든다.

-- 예매 (주문서). 환불의 성공·실패는 refund 가 가지므로 예매 상태에는 섞지 않는다.
CREATE TABLE booking (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 사용자에게 보이는 번호. id 를 노출하면 번호를 바꿔 가며 남의 예매를 조회하려는 시도가 쉬워진다.
    booking_no              VARCHAR(30)   NOT NULL,
    user_id                 BIGINT        NOT NULL,
    schedule_id             BIGINT        NOT NULL,
    -- 공연 단위 매수 검사와 조회에서 조인을 줄이려고 예매 때 복사해 둔다.
    performance_id          BIGINT        NOT NULL,
    status                  VARCHAR(20)   NOT NULL,
    receive_type            VARCHAR(20)   NOT NULL,
    -- 주문자 정보는 예매 시점의 값을 복사(스냅샷)한다. 나중에 회원이 바꾸거나 탈퇴해도 남아야 한다.
    orderer_name            VARCHAR(50)   NOT NULL,
    orderer_phone           VARCHAR(20)   NOT NULL,
    orderer_email           VARCHAR(255)  NOT NULL,
    recipient_name          VARCHAR(50),
    recipient_phone         VARCHAR(20),
    recipient_address       VARCHAR(500),
    carrier                 VARCHAR(50),
    tracking_no             VARCHAR(50),
    ticket_amount           INTEGER       NOT NULL,
    booking_fee_amount      INTEGER       NOT NULL,
    -- 처음 결제한 금액. 취소해도 바뀌지 않는다. 환불된 금액은 refund 를 합쳐서 안다.
    total_amount            INTEGER       NOT NULL,
    -- 예매 시점의 취소 규정 구간을 통째로 복사한다. 규정이 바뀌어도 이미 한 예매는 그대로다.
    cancel_policy_snapshot  JSONB         NOT NULL,
    -- 좌석 점유 시작 + 7분
    expires_at              TIMESTAMP     NOT NULL,
    canceled_at             TIMESTAMP,
    created_at              TIMESTAMP     NOT NULL,
    updated_at              TIMESTAMP     NOT NULL
);

CREATE UNIQUE INDEX uq_booking_no ON booking (booking_no);
-- 내 예매 목록
CREATE INDEX idx_booking_user ON booking (user_id, created_at DESC);
-- 1인 최대 매수 검사(공연 + 사용자)와 판매자의 공연별 예매 목록
CREATE INDEX idx_booking_performance_user ON booking (performance_id, user_id);
-- 판매자의 회차별 예매 목록
CREATE INDEX idx_booking_schedule ON booking (schedule_id);
-- 만료된 결제 대기 예매 정리. 결제 대기 건만 담겨서 작다.
CREATE INDEX idx_booking_pending_expires ON booking (expires_at) WHERE status = 'PENDING';

-- 예매 좌석. 구역·열·번호·등급·가격을 복사해 저장한다.
-- 끝난 회차의 판매 좌석을 지워도 "내가 어떤 좌석을 얼마에 샀는지"가 남아야 해서 schedule_seat_id 는 NULL 을 허용한다.
CREATE TABLE booking_seat (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT        NOT NULL,
    schedule_seat_id  BIGINT,
    zone_name         VARCHAR(50)   NOT NULL,
    row_label         VARCHAR(30)   NOT NULL,
    seat_number       VARCHAR(30)   NOT NULL,
    grade_name        VARCHAR(50)   NOT NULL,
    price             INTEGER       NOT NULL,
    booking_fee       INTEGER       NOT NULL,
    -- 취소하면 false. 취소된 좌석은 다시 팔릴 수 있어서 schedule_seat_id 에 단순 UNIQUE 를 걸 수 없다.
    active            BOOLEAN       NOT NULL,
    canceled_at       TIMESTAMP,
    cancel_fee        INTEGER,
    refund_id         BIGINT
);

CREATE INDEX idx_booking_seat_booking ON booking_seat (booking_id);
-- 같은 좌석이 두 사람에게 동시에 팔리는 사고를 DB 가 마지막으로 막는 장치. (락이 뚫려도 여기서 걸린다)
CREATE UNIQUE INDEX uq_booking_seat_active ON booking_seat (schedule_seat_id) WHERE active;

-- 결제. 결제 시도가 여러 번일 수 있어서 booking : payment = 1 : N 이다.
CREATE TABLE payment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT        NOT NULL,
    -- 토스에 보내는 orderId. 승인 요청이 두 번 처리되지 않게 하는 키로도 쓴다.
    order_id      VARCHAR(100)  NOT NULL,
    -- 토스 승인 후에만 생긴다.
    payment_key   VARCHAR(200),
    method        VARCHAR(50),
    -- 서버가 계산한 금액
    amount        INTEGER       NOT NULL,
    status        VARCHAR(20)   NOT NULL,
    fail_reason   VARCHAR(500),
    approved_at   TIMESTAMP,
    created_at    TIMESTAMP     NOT NULL
);

CREATE UNIQUE INDEX uq_payment_order_id ON payment (order_id);
-- payment_key 는 승인 전에는 비어 있어서 NULL 이 여러 개여도 UNIQUE 에 걸리지 않는다.
CREATE UNIQUE INDEX uq_payment_payment_key ON payment (payment_key);
CREATE INDEX idx_payment_booking ON payment (booking_id);
-- 결제 불일치 보정. 결제 준비 상태로 오래 남은 건만 담겨서 작다.
CREATE INDEX idx_payment_ready_created ON payment (created_at) WHERE status = 'READY';

-- 환불. 성공할 수도 실패할 수도 있고 여러 번 일어날 수 있어서 예매 상태와 따로 상태를 가진다.
CREATE TABLE refund (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id       BIGINT        NOT NULL,
    booking_id       BIGINT        NOT NULL,
    amount           INTEGER       NOT NULL,
    reason_type      VARCHAR(30)   NOT NULL,
    reason_detail    VARCHAR(500),
    -- 환불 행을 만들 때 정하는 UUID. 토스에 항상 같은 키를 보내서 응답이 끊겨도 이중 환불이 되지 않게 한다.
    idempotency_key  VARCHAR(100)  NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    retry_count      INTEGER       NOT NULL,
    fail_reason      VARCHAR(500),
    requested_at     TIMESTAMP     NOT NULL,
    completed_at     TIMESTAMP
);

CREATE UNIQUE INDEX uq_refund_idempotency_key ON refund (idempotency_key);
CREATE INDEX idx_refund_payment ON refund (payment_id);
CREATE INDEX idx_refund_booking ON refund (booking_id);
-- 환불 재시도·일괄 환불 스케줄러와 관리자의 실패 목록
CREATE INDEX idx_refund_status ON refund (status, requested_at);
